def glyph_to_bytes(rows):
    cols = []
    for c in range(5):
        b = 0
        for r in range(7):
            if rows[r][c] == '#':
                b |= (1 << r)
        cols.append(b)
    return cols

def main():
    out = []
    out.append("// Auto-generated by scripts/gen_font.py. Do not hand-edit.")
    out.append("// Column-major 5x7 font: 5 bytes per glyph, bit N of each byte = row N (0=top).")
    out.append("#pragma once")
    out.append("#include <stdint.h>")
    out.append("")
    out.append("#define FONT5X7_FIRST_CHAR ' '")
    out.append("#define FONT5X7_LAST_CHAR  0xB0")
    out.append("")
    chars = sorted(GLYPHS.keys(), key=lambda c: ord(c))
    lo = ord(min(chars, key=lambda c: ord(c)))
    hi = ord(max(chars, key=lambda c: ord(c)))
    out.append(f"// Sparse table covers 0x{lo:02X}..0x{hi:02X}; unknown chars render as blank.")
    out.append("typedef struct { uint8_t code; uint8_t col[5]; } font5x7_glyph_t;")
    out.append("static const font5x7_glyph_t FONT5X7_TABLE[] = {")
    for ch in chars:
        cols = glyph_to_bytes(GLYPHS[ch])
        code = ord(ch)
        comment = ch if ch not in ('\\', "'") else ('BACKSLASH' if ch == '\\' else "APOSTROPHE")
        out.append("    { 0x%02X, {0x%02X,0x%02X,0x%02X,0x%02X,0x%02X} }, // '%s'" % (code, cols[0], cols[1], cols[2], cols[3], cols[4], comment))
    out.append("};")
    out.append(f"#define FONT5X7_TABLE_LEN {len(chars)}")
    print("\n".join(out))

if __name__ == '__main__':
    main()
